/**
 * 등록되지 않은 이모지도 문자의 해시값을 이용해 항상 고유하고 예쁜 파스텔톤 HSL 색상을 생성합니다.
 */
function generatePastelColor(str) {
  if (!str) return '#f0f0f0'

  let hash = 0
  for (let i = 0; i < str.length; i++) {
    hash = str.charCodeAt(i) + ((hash << 5) - hash)
  }

  const h = Math.abs(hash) % 360
  const s = 70 + (Math.abs(hash >> 2) % 10) // 채도 70~80% (화사한 색상)
  const l = 88 + (Math.abs(hash >> 4) % 6)  // 명도 88~94% (부드러운 파스텔)

  return `hsl(${h}, ${s}%, ${l}%)`
}

/**
 * 이모지에 맞는 배경색을 반환합니다.
 * ICON_COLORS에 등록된 색상이 없으면 고유 파스텔 배경색을 동적으로 생성합니다.
 */
export function getFoodIconBackground(icon) {
  if (!icon) return '#f0f0f0'
  return ICON_COLORS[icon] ?? generatePastelColor(icon)
}

/**
 * 입력된 음식 이름을 기반으로 가장 어울리는 이모지를 추론합니다.
 */
export function guessFoodIcon(name) {
  if (!name) return null
  const n = name.toLowerCase().trim()
  const match = NAME_TO_ICON.find(([keywords]) => keywords.some(keyword => n.includes(keyword)))
  return match?.[1] ?? null
}